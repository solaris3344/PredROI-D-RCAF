class ConvBlock(nn.Module):
    def __init__(self, c_in, c_out):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(c_in, c_out, 3, padding=1, bias=False),
            nn.BatchNorm2d(c_out),
            nn.GELU(),
            nn.Conv2d(c_out, c_out, 3, padding=1, bias=False),
            nn.BatchNorm2d(c_out),
            nn.GELU(),
        )

    def forward(self, x):
        return self.block(x)


class UpBlock(nn.Module):
    def __init__(self, c_in, c_skip, c_out):
        super().__init__()
        self.conv = ConvBlock(c_in + c_skip, c_out)

    def forward(self, x, skip):
        x = F.interpolate(
            x,
            size=skip.shape[-2:],
            mode="bilinear",
            align_corners=False,
        )
        return self.conv(torch.cat([x, skip], dim=1))


class ResNet18UNet(nn.Module):
    def __init__(self, pretrained=True):
        super().__init__()

        enc = timm.create_model(
            "resnet18",
            pretrained=pretrained,
            features_only=True,
            out_indices=(0, 1, 2, 3, 4),
        )

        self.encoder = enc
        ch = list(enc.feature_info.channels())

        self.up4 = UpBlock(ch[4], ch[3], 256)
        self.up3 = UpBlock(256, ch[2], 128)
        self.up2 = UpBlock(128, ch[1], 64)
        self.up1 = UpBlock(64, ch[0], 32)

        self.head = nn.Sequential(
            ConvBlock(32, 32),
            nn.Conv2d(32, 1, 1),
        )

    def forward(self, x):
        input_hw = x.shape[-2:]
        f0, f1, f2, f3, f4 = self.encoder(x)

        x = self.up4(f4, f3)
        x = self.up3(x, f2)
        x = self.up2(x, f1)
        x = self.up1(x, f0)

        logits = self.head(x)
        logits = F.interpolate(
            logits,
            size=input_hw,
            mode="bilinear",
            align_corners=False,
        )

        return logits


def balanced_bce_with_logits(logits, target):
    raw = F.binary_cross_entropy_with_logits(
        logits.float(),
        target.float(),
        reduction="none",
    )

    pos = target.float().sum()
    total = torch.tensor(
        target.numel(),
        device=target.device,
        dtype=torch.float32,
    )
    neg = total - pos

    if pos <= 0 or neg <= 0:
        return raw.mean()

    pos_w = torch.clamp(total / (2.0 * pos), 0.25, 12.0)
    neg_w = torch.clamp(total / (2.0 * neg), 0.25, 12.0)

    w = target.float() * pos_w + (1.0 - target.float()) * neg_w
    return (raw * w).mean()


def soft_dice_loss(logits, target):
    prob = torch.sigmoid(logits.float())
    target = target.float()

    inter = (prob * target).sum((1, 2, 3))
    denom = prob.sum((1, 2, 3)) + target.sum((1, 2, 3))

    dice = (2.0 * inter + 1.0) / (denom + 1.0)
    return (1.0 - dice).mean()


def segmentation_loss(logits, target):
    bce = balanced_bce_with_logits(logits, target)
    dice = soft_dice_loss(logits, target)
    return 0.5 * bce + 0.5 * dice


def hard_iou_from_logits(logits, target, threshold=0.5):
    pred = (torch.sigmoid(logits.float()) >= threshold).float()
    target = target.float()

    inter = (pred * target).sum((1, 2, 3))
    union = ((pred + target) > 0).float().sum((1, 2, 3))

    return ((inter + 1e-6) / (union + 1e-6)).mean()


def train_segmenter(
    train_patients,
    args,
    device,
    seed,
    tag,
):
    common.seed_all(seed, args.deterministic)

    rows = slice_rows_from_patients(train_patients)

    ds = SegDataset(
        rows,
        args.mat_root,
        args.seg_size,
        True,
        seed,
    )

    loader = DataLoader(
        ds,
        batch_size=args.seg_batch_size,
        shuffle=True,
        num_workers=args.workers,
        pin_memory=(device.type == "cuda"),
    )

    model = ResNet18UNet(
        pretrained=not args.no_pretrained,
    ).to(device)

    opt = torch.optim.AdamW(
        model.parameters(),
        lr=args.seg_lr,
        weight_decay=args.seg_weight_decay,
    )

    scaler = torch.amp.GradScaler(
        "cuda",
        enabled=(
            device.type == "cuda"
            and args.amp_dtype == "fp16"
        ),
    )

    sched = torch.optim.lr_scheduler.CosineAnnealingLR(
        opt,
        T_max=max(1, args.seg_epochs),
        eta_min=1e-6,
    )

    print(
        f"[SEG {tag}] patients={len(train_patients)} "
        f"slices={len(rows)} epochs={args.seg_epochs}"
    )

    for epoch in range(1, args.seg_epochs + 1):
        ds.set_epoch(epoch)
        model.train()

        losses = []
        ious = []

        for batch in loader:
            x = batch["image"].to(device, non_blocking=True)
            m = batch["mask"].to(device, non_blocking=True)

            opt.zero_grad(set_to_none=True)

            with common.autocast_ctx(device, args.amp_dtype):
                logits = model(x)

            loss = segmentation_loss(
                logits.float(),
                m.float(),
            )

            if not torch.isfinite(loss):
                raise FloatingPointError(
                    f"Non-finite segmentation loss {tag} epoch={epoch}"
                )

            scaler.scale(loss).backward()
            scaler.unscale_(opt)

            gnorm = torch.nn.utils.clip_grad_norm_(
                model.parameters(),
                3.0,
            )

            if not torch.isfinite(gnorm):
                raise FloatingPointError(
                    f"Non-finite segmentation grad norm {tag} epoch={epoch}"
                )

            scaler.step(opt)
            scaler.update()

            losses.append(float(loss.detach().cpu()))
            with torch.no_grad():
                ious.append(
                    float(
                        hard_iou_from_logits(
                            logits,
                            m,
                        ).detach().cpu()
                    )
                )

        sched.step()

        print(
            f"    seg epoch {epoch:02d}/{args.seg_epochs} | "
            f"loss={np.mean(losses):.4f} "
            f"train-IoU={np.mean(ious):.3f}"
        )

    return model


