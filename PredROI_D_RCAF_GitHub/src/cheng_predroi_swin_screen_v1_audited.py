SEG_MEAN = common.IMAGENET_MEAN
SEG_STD = common.IMAGENET_STD


def load_full_image_and_mask(
    path: str,
    mat_root: Path,
    seg_size: int,
    train: bool,
    rng: np.random.Generator,
):
    img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise RuntimeError(f"Could not read {path}")

    mask = read_aligned_mask(path, mat_root)

    if img.shape != mask.shape:
        raise RuntimeError(
            f"Image/mask shape mismatch: {path}: {img.shape} vs {mask.shape}"
        )

    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8),
    )
    img = clahe.apply(img)

    if train:
        if rng.random() < 0.5:
            img = cv2.flip(img, 1)
            mask = cv2.flip(mask, 1)

        angle = float(rng.uniform(-5.0, 5.0))
        scale = float(rng.uniform(0.97, 1.03))
        h, w = img.shape

        M = cv2.getRotationMatrix2D(
            (w / 2.0, h / 2.0),
            angle,
            scale,
        )

        img = cv2.warpAffine(
            img,
            M,
            (w, h),
            flags=cv2.INTER_LINEAR,
            borderMode=cv2.BORDER_REFLECT_101,
        )

        mask = cv2.warpAffine(
            mask,
            M,
            (w, h),
            flags=cv2.INTER_NEAREST,
            borderMode=cv2.BORDER_CONSTANT,
            borderValue=0,
        )

    img = cv2.resize(
        img,
        (seg_size, seg_size),
        interpolation=cv2.INTER_AREA,
    )

    mask = cv2.resize(
        mask,
        (seg_size, seg_size),
        interpolation=cv2.INTER_NEAREST,
    )

    mask = (mask > 0).astype(np.float32)

    if float(mask.sum()) <= 0:
        raise RuntimeError(f"Mask disappeared after transform: {path}")

    x = torch.from_numpy(
        img.astype(np.float32) / 255.0
    ).unsqueeze(0)

    x = x.repeat(3, 1, 1)
    x = (x - SEG_MEAN) / SEG_STD

    m = torch.from_numpy(mask).unsqueeze(0)

    return x, m


class SegDataset(Dataset):
    def __init__(
        self,
        rows,
        mat_root,
        seg_size,
        train,
        seed,
    ):
        self.rows = list(rows)
        self.mat_root = Path(mat_root)
        self.seg_size = int(seg_size)
        self.train = bool(train)
        self.seed = int(seed)
        self.epoch = 0

    def set_epoch(self, epoch):
        self.epoch = int(epoch)

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, idx):
        r = self.rows[idx]
        rng = np.random.default_rng(
            self.seed + self.epoch * 100003 + idx * 997
        )

        x, m = load_full_image_and_mask(
            r["path"],
            self.mat_root,
            self.seg_size,
            self.train,
            rng,
        )

        return {
            "image": x,
            "mask": m,
            "path": str(r["path"]),
            "patient_id": str(r["patient_id"]),
            "label": int(r["label"]),
        }


