def expand_square_box(
    box: dict,
    image_hw: Tuple[int, int],
    margin_factor: float,
):
    H, W = image_hw

    if not bool(box["found"]):
        return {
            "x0": 0,
            "y0": 0,
            "x1": W - 1,
            "y1": H - 1,
            "fallback_full_image": True,
        }

    x0 = float(box["x0"])
    y0 = float(box["y0"])
    x1 = float(box["x1"])
    y1 = float(box["y1"])

    cx = 0.5 * (x0 + x1)
    cy = 0.5 * (y0 + y1)

    side = max(
        1.0,
        max(x1 - x0 + 1.0, y1 - y0 + 1.0)
        * float(margin_factor),
    )

    return {
        "cx": cx,
        "cy": cy,
        "side": side,
        "fallback_full_image": False,
    }


def crop_from_box(
    image: np.ndarray,
    box: dict,
    margin_factor: float,
):
    H, W = image.shape

    info = expand_square_box(
        box,
        (H, W),
        margin_factor,
    )

    if info["fallback_full_image"]:
        return image.copy()

    cx = float(info["cx"])
    cy = float(info["cy"])
    side = max(1, int(math.ceil(float(info["side"]))))

    if side % 2 == 0:
        side += 1

    half = side // 2
    center_x = int(round(cx))
    center_y = int(round(cy))

    left = center_x - half
    right = center_x + half + 1
    top = center_y - half
    bottom = center_y + half + 1

    pad_left = max(0, -left)
    pad_right = max(0, right - W)
    pad_top = max(0, -top)
    pad_bottom = max(0, bottom - H)

    if pad_left or pad_right or pad_top or pad_bottom:
        image = cv2.copyMakeBorder(
            image,
            pad_top,
            pad_bottom,
            pad_left,
            pad_right,
            borderType=cv2.BORDER_REFLECT_101,
        )

        left += pad_left
        right += pad_left
        top += pad_top
        bottom += pad_top

    crop = image[top:bottom, left:right]

    if crop.shape != (side, side):
        raise RuntimeError(
            f"Predicted ROI crop geometry failed: expected {(side,side)}, "
            f"got {crop.shape}"
        )

    return crop


def load_predroi_image(
    path: str,
    box: dict,
    image_size: int,
    train: bool,
    rng: np.random.Generator,
    margin_factor: float,
):
    img = cv2.imread(path, cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise RuntimeError(f"Could not read {path}")

    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8),
    )
    img = clahe.apply(img)

    crop = crop_from_box(
        img,
        box,
        margin_factor,
    )

    # Classification augmentation is applied AFTER predicted cropping.
    # This preserves the predicted ROI while matching the baseline's small
    # geometric perturbation family.
    if train:
        if rng.random() < 0.5:
            crop = cv2.flip(crop, 1)

        angle = float(rng.uniform(-5.0, 5.0))
        scale = float(rng.uniform(0.97, 1.03))
        h, w = crop.shape

        M = cv2.getRotationMatrix2D(
            (w / 2.0, h / 2.0),
            angle,
            scale,
        )

        crop = cv2.warpAffine(
            crop,
            M,
            (w, h),
            flags=cv2.INTER_LINEAR,
            borderMode=cv2.BORDER_REFLECT_101,
        )

    crop = cv2.resize(
        crop,
        (image_size, image_size),
        interpolation=cv2.INTER_AREA,
    )

    x = torch.from_numpy(
        crop.astype(np.float32) / 255.0
    ).unsqueeze(0)

    x = x.repeat(3, 1, 1)
    x = (x - common.IMAGENET_MEAN) / common.IMAGENET_STD

    return x


class PredROIDataset(Dataset):
    def __init__(
        self,
        rows,
        box_lookup,
        image_size,
        train,
        seed,
        margin_factor,
    ):
        self.rows = list(rows)
        self.box_lookup = box_lookup
        self.image_size = int(image_size)
        self.train = bool(train)
        self.seed = int(seed)
        self.margin_factor = float(margin_factor)
        self.epoch = 0

    def set_epoch(self, epoch):
        self.epoch = int(epoch)

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, idx):
        r = self.rows[idx]
        path = str(r["path"])

        if path not in self.box_lookup:
            raise RuntimeError(f"Missing predicted box for {path}")

        rng = np.random.default_rng(
            self.seed + self.epoch * 100003 + idx * 997
        )

        x = load_predroi_image(
            path,
            self.box_lookup[path],
            self.image_size,
            self.train,
            rng,
            self.margin_factor,
        )

        return {
            "image": x,
            "label": torch.tensor(int(r["label"]), dtype=torch.long),
            "patient_id": str(r["patient_id"]),
            "path": path,
        }


class SwinClassifier(nn.Module):
    def __init__(self, backbone, pretrained=True, dropout=0.15):
        super().__init__()

        self.encoder = timm.create_model(
            backbone,
            pretrained=pretrained,
            num_classes=0,
            global_pool="avg",
        )

        dim = int(self.encoder.num_features)
        self.dropout = nn.Dropout(dropout)
        self.classifier = nn.Linear(dim, N_CLASSES)

    def forward(self, x):
        f = self.encoder(x)
        return self.classifier(self.dropout(f))


def set_encoder_trainable(model, trainable):
    for p in model.encoder.parameters():
        p.requires_grad = bool(trainable)


def make_classifier_optimizer(
    model,
    backbone_lr,
    head_lr,
    weight_decay,
):
    bb, head = [], []

    for name, p in model.named_parameters():
        if name.startswith("encoder."):
            bb.append(p)
        else:
            head.append(p)

    return torch.optim.AdamW(
        [
            {"params": bb, "lr": backbone_lr},
            {"params": head, "lr": head_lr},
        ],
        weight_decay=weight_decay,
    )


