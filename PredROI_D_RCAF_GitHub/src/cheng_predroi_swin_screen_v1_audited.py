def decode_pid(arr: np.ndarray) -> str:
    a = np.asarray(arr).reshape(-1)
    if np.issubdtype(a.dtype, np.integer):
        return "".join(chr(int(v)) for v in a if int(v) != 0).strip()
    return str(a.tolist())


def align_mat_spatial_array(x: np.ndarray) -> np.ndarray:
    a = np.asarray(x)
    if a.ndim != 2:
        raise RuntimeError(f"Expected 2-D MAT spatial array, got {a.shape}")
    return a.T.copy()


def mat_path_for_png(png_path: str, mat_root: Path) -> Path:
    return mat_root / f"{Path(png_path).stem}.mat"


def read_aligned_mask(png_path: str, mat_root: Path) -> np.ndarray:
    mp = mat_path_for_png(png_path, mat_root)
    if not mp.exists():
        raise FileNotFoundError(mp)

    with h5py.File(mp, "r") as f:
        raw = np.asarray(f["cjdata"]["tumorMask"])

    mask = (align_mat_spatial_array(raw) > 0).astype(np.uint8)

    if int(mask.sum()) <= 0:
        raise RuntimeError(f"Empty tumor mask: {mp}")

    return mask


def read_mat_pid(png_path: str, mat_root: Path) -> str:
    mp = mat_path_for_png(png_path, mat_root)

    with h5py.File(mp, "r") as f:
        return decode_pid(np.asarray(f["cjdata"]["PID"]))


def slice_rows_from_patients(patients) -> List[dict]:
    rows = []
    for p in patients:
        for q in p.paths:
            rows.append(
                {
                    "path": str(q),
                    "patient_id": str(p.patient_id),
                    "label": int(p.label),
                }
            )
    return rows


def group_patients_by_ids(patients, ids):
    ids = set(map(str, ids))
    return [p for p in patients if str(p.patient_id) in ids]


