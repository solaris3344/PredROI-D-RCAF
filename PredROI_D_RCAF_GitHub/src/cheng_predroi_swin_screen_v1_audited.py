def aggregate_patient_probs(slice_rows):
    by_pid = defaultdict(list)

    for r in slice_rows:
        by_pid[str(r["patient_id"])].append(r)

    out = []

    for pid, rr in sorted(by_pid.items()):
        ys = {int(x["true_id"]) for x in rr}

        if len(ys) != 1:
            raise RuntimeError(f"Inconsistent patient labels: {pid}")

        y = next(iter(ys))

        P = np.asarray(
            [
                [x[f"prob_{c}"] for c in CLASSES]
                for x in rr
            ],
            dtype=np.float64,
        )

        p = P.mean(axis=0)
        pred = int(np.argmax(p))

        rec = {
            "patient_id": pid,
            "true_id": y,
            "pred_id": pred,
            "correct": int(pred == y),
            "n_slices": int(len(rr)),
        }

        for c, cname in enumerate(CLASSES):
            rec[f"mean_prob_{cname}"] = float(p[c])

        out.append(rec)

    return out


def patient_metrics(rows):
    y = np.asarray([int(r["true_id"]) for r in rows], dtype=int)
    p = np.asarray([int(r["pred_id"]) for r in rows], dtype=int)

    rec = recall_score(
        y,
        p,
        labels=list(range(N_CLASSES)),
        average=None,
        zero_division=0,
    )

    return {
        "n": int(len(y)),
        "accuracy": float(100.0 * accuracy_score(y, p)),
        "macro_f1": float(
            100.0
            * f1_score(
                y,
                p,
                labels=list(range(N_CLASSES)),
                average="macro",
                zero_division=0,
            )
        ),
        "glioma_recall": float(100.0 * rec[0]),
        "meningioma_recall": float(100.0 * rec[1]),
        "pituitary_recall": float(100.0 * rec[2]),
        "errors": int(np.sum(y != p)),
        "confusion_matrix": confusion_matrix(
            y,
            p,
            labels=list(range(N_CLASSES)),
        ).tolist(),
    }


def slice_metrics(rows):
    y = np.asarray([int(r["true_id"]) for r in rows], dtype=int)
    p = np.asarray([int(r["slice_pred_id"]) for r in rows], dtype=int)

    return {
        "n": int(len(y)),
        "accuracy": float(100.0 * accuracy_score(y, p)),
        "macro_f1": float(
            100.0 * f1_score(
                y,
                p,
                average="macro",
                zero_division=0,
            )
        ),
        "errors": int(np.sum(y != p)),
    }


def train_classifier(
    inner_train,
    inner_val,
    train_boxes,
    val_boxes,
    args,
    device,
    out_root: Path,
):
    common.seed_all(
        args.outer_seed * 50000 + args.outer_fold,
        args.deterministic,
    )

    train_rows = slice_rows_from_patients(inner_train)
    val_rows = slice_rows_from_patients(inner_val)

    train_lookup = {
        str(r["path"]): r
        for r in train_boxes
    }

    val_lookup = {
        str(r["path"]): r
        for r in val_boxes
    }

    if set(train_lookup) != {r["path"] for r in train_rows}:
        raise RuntimeError("Classifier train box coverage mismatch.")

    if set(val_lookup) != {r["path"] for r in val_rows}:
        raise RuntimeError("Classifier val box coverage mismatch.")

    tr_ds = PredROIDataset(
        train_rows,
        train_lookup,
        args.image_size,
        True,
        args.outer_seed * 51000 + args.outer_fold,
        args.crop_margin_factor,
    )

    va_ds = PredROIDataset(
        val_rows,
        val_lookup,
        args.image_size,
        False,
        args.outer_seed * 52000 + args.outer_fold,
        args.crop_margin_factor,
    )

    tr_loader = DataLoader(
        tr_ds,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.workers,
        pin_memory=(device.type == "cuda"),
    )

    va_loader = DataLoader(
        va_ds,
        batch_size=args.eval_batch_size,
        shuffle=False,
        num_workers=args.workers,
        pin_memory=(device.type == "cuda"),
    )

    model = SwinClassifier(
        args.backbone,
        pretrained=not args.no_pretrained,
        dropout=args.dropout,
    ).to(device)

    cw = common.patient_class_weights(
        inner_train,
        device,
    )

    criterion = common.FocalLoss(
        cw,
        gamma=args.focal_gamma,
        label_smoothing=args.label_smoothing,
    )

    set_encoder_trainable(model, False)

    opt = make_classifier_optimizer(
        model,
        args.backbone_lr,
        args.head_lr,
        args.weight_decay,
    )

    scaler = torch.amp.GradScaler(
        "cuda",
        enabled=(
            device.type == "cuda"
            and args.amp_dtype == "fp16"
        ),
    )

    sched = torch.optim.lr_scheduler.CosineAnnealingLR(
        opt,
        T_max=max(1, args.max_select_epochs),
        eta_min=args.minimum_lr,
    )

    history = []
    best = None
    best_slice_rows = None
    best_patient_rows = None

    for epoch in range(1, args.max_select_epochs + 1):
        tr_ds.set_epoch(epoch)
        set_encoder_trainable(
            model,
            epoch > args.freeze_epochs,
        )

        model.train()
        opt.zero_grad(set_to_none=True)

        losses = []
        correct = 0
        n = 0

        for step, batch in enumerate(tr_loader, start=1):
            x = batch["image"].to(device, non_blocking=True)
            y = batch["label"].to(device, non_blocking=True)

            with common.autocast_ctx(device, args.amp_dtype):
                logits = model(x)
                loss = criterion(logits, y)
                scaled_loss = loss / args.accumulation_steps

            if not torch.isfinite(loss):
                raise FloatingPointError(
                    f"Non-finite classifier loss epoch={epoch}"
                )

            scaler.scale(scaled_loss).backward()

            if (
                step % args.accumulation_steps == 0
                or step == len(tr_loader)
            ):
                scaler.unscale_(opt)

                grad_params = [
                    p
                    for p in model.parameters()
                    if p.requires_grad and p.grad is not None
                ]

                gnorm = torch.nn.utils.clip_grad_norm_(
                    grad_params,
                    args.grad_clip,
                )

                if not torch.isfinite(gnorm):
                    raise FloatingPointError(
                        f"Non-finite classifier grad norm epoch={epoch}"
                    )

                scaler.step(opt)
                scaler.update()
                opt.zero_grad(set_to_none=True)

            losses.append(float(loss.detach().cpu()))
            correct += int((logits.argmax(1) == y).sum().item())
            n += int(y.numel())

        # Image-only predicted-crop validation; no oracle crop.
        model.eval()
        srows = []

        with torch.no_grad():
            for batch in va_loader:
                x = batch["image"].to(device, non_blocking=True)
                y = batch["label"].cpu().numpy()

                with common.autocast_ctx(device, args.amp_dtype):
                    prob = F.softmax(
                        model(x),
                        dim=-1,
                    ).float().cpu().numpy()

                pred = prob.argmax(axis=1)

                for i in range(len(y)):
                    rec = {
                        "patient_id": str(batch["patient_id"][i]),
                        "path": str(batch["path"][i]),
                        "true_id": int(y[i]),
                        "slice_pred_id": int(pred[i]),
                    }

                    for c, cname in enumerate(CLASSES):
                        rec[f"prob_{cname}"] = float(prob[i, c])

                    srows.append(rec)

        prows = aggregate_patient_probs(srows)
        sm = slice_metrics(srows)
        pm = patient_metrics(prows)

        tracc = 100.0 * correct / max(1, n)

        history.append(
            {
                "epoch": epoch,
                "train_loss": float(np.mean(losses)),
                "train_slice_acc": tracc,
                "inner_patient_acc": pm["accuracy"],
                "inner_patient_f1": pm["macro_f1"],
                "inner_patient_errors": pm["errors"],
                "inner_slice_acc": sm["accuracy"],
                "inner_slice_f1": sm["macro_f1"],
            }
        )

        print(
            f"[CLS] epoch {epoch:02d}/{args.max_select_epochs} | "
            f"loss={np.mean(losses):.4f} train-slice={tracc:6.2f}% | "
            f"INNER patient Acc={pm['accuracy']:6.2f}% "
            f"F1={pm['macro_f1']:6.2f}% err={pm['errors']} | "
            f"slice Acc={sm['accuracy']:6.2f}%"
        )

        if epoch > args.freeze_epochs:
            key = (
                pm["macro_f1"],
                pm["accuracy"],
                -epoch,
            )

            if best is None or key > best["key"]:
                best = {
                    "key": key,
                    "epoch": int(epoch),
                    "patient": pm,
                    "slice": sm,
                }
                best_slice_rows = [dict(r) for r in srows]
                best_patient_rows = [dict(r) for r in prows]

        sched.step()

    if best is None:
        raise RuntimeError("No selectable PredROI classifier epoch.")

    pd.DataFrame(history).to_csv(
        out_root / "classifier_inner_selection_history.csv",
        index=False,
    )

    pd.DataFrame(best_slice_rows).to_csv(
        out_root / "best_inner_slice_predictions.csv",
        index=False,
    )

    pd.DataFrame(best_patient_rows).to_csv(
        out_root / "best_inner_patient_predictions.csv",
        index=False,
    )

    return best


