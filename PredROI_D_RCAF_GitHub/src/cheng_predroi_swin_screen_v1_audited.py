def largest_component_bbox(binary_mask: np.ndarray):
    m = (np.asarray(binary_mask) > 0).astype(np.uint8)

    n, labels, stats, _ = cv2.connectedComponentsWithStats(
        m,
        connectivity=8,
    )

    if n <= 1:
        return None

    # Skip background row 0.
    areas = stats[1:, cv2.CC_STAT_AREA]
    idx = 1 + int(np.argmax(areas))

    x = int(stats[idx, cv2.CC_STAT_LEFT])
    y = int(stats[idx, cv2.CC_STAT_TOP])
    w = int(stats[idx, cv2.CC_STAT_WIDTH])
    h = int(stats[idx, cv2.CC_STAT_HEIGHT])
    area = int(stats[idx, cv2.CC_STAT_AREA])

    return {
        "x0": x,
        "y0": y,
        "x1": x + w - 1,
        "y1": y + h - 1,
        "area": area,
    }


def prob_to_bbox(
    prob: np.ndarray,
    original_hw: Tuple[int, int],
    threshold_primary: float,
    threshold_fallback: float,
):
    p = np.asarray(prob, np.float32)

    bbox = largest_component_bbox(
        p >= threshold_primary
    )

    used_threshold = threshold_primary

    if bbox is None:
        bbox = largest_component_bbox(
            p >= threshold_fallback
        )
        used_threshold = threshold_fallback

    H0, W0 = original_hw
    H, W = p.shape

    if bbox is None:
        return {
            "found": False,
            "threshold": float("nan"),
            "x0": 0.0,
            "y0": 0.0,
            "x1": float(W0 - 1),
            "y1": float(H0 - 1),
            "area_fraction_seg": 0.0,
        }

    sx = W0 / float(W)
    sy = H0 / float(H)

    x0 = bbox["x0"] * sx
    x1 = (bbox["x1"] + 1) * sx - 1
    y0 = bbox["y0"] * sy
    y1 = (bbox["y1"] + 1) * sy - 1

    return {
        "found": True,
        "threshold": float(used_threshold),
        "x0": float(x0),
        "y0": float(y0),
        "x1": float(x1),
        "y1": float(y1),
        "area_fraction_seg": float(
            bbox["area"] / max(1, H * W)
        ),
    }


@torch.no_grad()
def predict_boxes(
    model,
    patients,
    args,
    device,
    seed,
    tag,
    evaluate_with_masks=True,
):
    rows = slice_rows_from_patients(patients)

    ds = SegDataset(
        rows,
        args.mat_root,
        args.seg_size,
        False,
        seed,
    )

    loader = DataLoader(
        ds,
        batch_size=args.seg_eval_batch_size,
        shuffle=False,
        num_workers=args.workers,
        pin_memory=(device.type == "cuda"),
    )

    model.eval()
    out = []

    for batch in loader:
        x = batch["image"].to(device, non_blocking=True)
        m = batch["mask"].to(device, non_blocking=True)

        with common.autocast_ctx(device, args.amp_dtype):
            logits = model(x)

        prob = torch.sigmoid(logits.float()).cpu().numpy()[:, 0]

        for i in range(len(prob)):
            path = str(batch["path"][i])
            original = cv2.imread(path, cv2.IMREAD_GRAYSCALE)

            if original is None:
                raise RuntimeError(f"Could not read source image: {path}")

            rec = prob_to_bbox(
                prob[i],
                original.shape,
                args.box_threshold,
                args.box_fallback_threshold,
            )

            rec.update(
                {
                    "path": path,
                    "patient_id": str(batch["patient_id"][i]),
                    "label": int(batch["label"][i]),
                    "source": tag,
                }
            )

            if evaluate_with_masks:
                gt = m[i, 0].cpu().numpy() > 0.5
                pr = prob[i] >= args.box_threshold

                inter = int(np.logical_and(gt, pr).sum())
                union = int(np.logical_or(gt, pr).sum())

                rec["seg_iou_050"] = float(
                    inter / union if union > 0 else 0.0
                )

            out.append(rec)

    return out


